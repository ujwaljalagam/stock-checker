-- Portable between H2 (MODE=PostgreSQL) and PostgreSQL.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(254) NOT NULL UNIQUE,
    created_at  BIGINT NOT NULL
);

CREATE TABLE login_codes (
    email       VARCHAR(254) PRIMARY KEY,
    code_hash   VARCHAR(64) NOT NULL,
    expires_at  BIGINT NOT NULL,
    attempts    INT NOT NULL DEFAULT 0,
    created_at  BIGINT NOT NULL
);

CREATE TABLE sessions (
    token_hash  VARCHAR(64) PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  BIGINT NOT NULL,
    expires_at  BIGINT NOT NULL
);
CREATE INDEX idx_sessions_user ON sessions(user_id);

CREATE TABLE watches (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    retailer         VARCHAR(32) NOT NULL,
    sku              VARCHAR(64) NOT NULL,
    product_name     VARCHAR(200),
    product_url      VARCHAR(500),
    zip              VARCHAR(10) NOT NULL,
    radius_miles     INT NOT NULL,
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    last_status      VARCHAR(16) NOT NULL DEFAULT 'UNKNOWN',
    last_checked_at  BIGINT,
    last_store_name  VARCHAR(200),
    last_error       VARCHAR(500),
    last_alert_at    BIGINT,
    created_at       BIGINT NOT NULL
);
CREATE INDEX idx_watches_user ON watches(user_id);
CREATE INDEX idx_watches_due ON watches(active, last_checked_at);

CREATE TABLE push_subscriptions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    endpoint    VARCHAR(1000) NOT NULL UNIQUE,
    p256dh      VARCHAR(200) NOT NULL,
    auth        VARCHAR(100) NOT NULL,
    user_agent  VARCHAR(300),
    created_at  BIGINT NOT NULL,
    last_success_at BIGINT,
    failures    INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_push_user ON push_subscriptions(user_id);

CREATE TABLE alerts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    watch_id      BIGINT NOT NULL REFERENCES watches(id) ON DELETE CASCADE,
    status        VARCHAR(16) NOT NULL,
    title         VARCHAR(300) NOT NULL,
    body          VARCHAR(1000) NOT NULL,
    url           VARCHAR(500),
    store_name    VARCHAR(200),
    receipt_hash  VARCHAR(64) NOT NULL,
    created_at    BIGINT NOT NULL,
    push_sent_at  BIGINT,
    shown_at      BIGINT,
    emailed_at    BIGINT
);
CREATE INDEX idx_alerts_user ON alerts(user_id, created_at);
CREATE INDEX idx_alerts_fallback ON alerts(shown_at, emailed_at, created_at);
